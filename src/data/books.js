export function getBook(id) {
  return books.find((book) => book.id === id);
}

export function booksInCategory(name) {
  return books.filter((book) => book.category === name);
}

export function relatedBooks(book, limit = 4) {
  return books
    .filter((item) => item.category === book.category && item.id !== book.id)
    .slice(0, limit);
}
